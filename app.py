# Importing the required libraries for data processing,
# model loading, numerical calculations, and API development.
import pandas as pd
import joblib
import numpy as np
# Importing FastAPI components for creating the API
# and handling HTTP exceptions.
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from fastapi.middleware.cors import CORSMiddleware

# Initializing the FastAPI application.
app = FastAPI()
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "https://adarsh-insurance-incentive-predicti.vercel.app"
       
    ],
    allow_credentials=False,
    allow_methods=["POST", "OPTIONS"],
    allow_headers=["Content-Type"],
)

# Defining the structure of the incoming request data.
# The API expects a list of lists containing customer information.
class RevenueRenewal(BaseModel):
    data: list[list]


# ---------------------------------------------------------
# Agent Effort Calculation
# ---------------------------------------------------------
# This function estimates the effort generated by an agent
# based on the incentive amount provided.
#
# The exponential function represents diminishing returns,
# meaning that increasing the incentive increases effort,
# but the increase gradually becomes smaller.
def agent_effort(incentive_amount):
    return 10*(1-np.exp(-incentive_amount/400))


# ---------------------------------------------------------
# Agent Probability Calculation
# ---------------------------------------------------------
# This function converts the calculated agent effort into
# an additional probability of successful policy renewal.
#
# The function also follows a diminishing-return pattern.
def agent_proba(effort):
    return 0.20*(1-np.exp(-effort/5))


class probabilities:
    """Concrete probability calculations used by the incentive optimizer.

    The methods accept either scalars or array-like values so they can be
    reused for individual customers as well as batches of predictions.
    """

    @staticmethod
    def agent_effort(incentive_amount):
        """Calculate agent effort generated by an incentive amount."""
        return 10 * (1 - np.exp(-np.asarray(incentive_amount) / 400))

    @staticmethod
    def agent_proba(effort):
        """Calculate the additional renewal probability from agent effort."""
        return 0.20 * (1 - np.exp(-np.asarray(effort) / 5))

    @classmethod
    def renewal_probability(cls, base_probability, incentive_amount):
        """Calculate renewal probability after applying an incentive."""
        probability = np.asarray(base_probability) + cls.agent_proba(
            cls.agent_effort(incentive_amount)
        )
        return np.clip(probability, 0, 1)

    @classmethod
    def revenue(cls, premium, base_probability, incentive_amount):
        """Calculate expected revenue for a premium and incentive amount."""
        return np.asarray(premium) * cls.renewal_probability(
            base_probability, incentive_amount
        ) - np.asarray(incentive_amount)


# ---------------------------------------------------------
# Revenue Calculation
# ---------------------------------------------------------
# This function calculates the expected revenue by combining
# the premium, base renewal probability, additional probability
# generated by the agent, and the incentive cost.
def rev(premium, probability, agent_prob, incentive_amount):
    return premium * (probability + agent_prob)-incentive_amount


class prediction:
    """Load the renewal model and optimize incentives for customer records."""

    def __init__(self, model_path="renewal_pipeline.pkl"):
        self.model = joblib.load(model_path)

    def predict_proba(self, data):
        """Return renewal probabilities for the model feature columns."""
        return self.model.predict_proba(data)

    def optimize_revenue(self, data, probabilities):
        """Select the incentive producing the highest expected revenue."""
        results = []
        for premium, base_prob in zip(data["premium"], probabilities[:, 1]):
            best_revenue = base_prob * premium
            best_incentive = 0
            for incentive in range(500, 5000, 500):
                revenue = rev(
                    premium,
                    base_prob,
                    agent_proba(agent_effort(incentive)),
                    incentive,
                )
                if revenue > best_revenue:
                    best_revenue = revenue
                    best_incentive = incentive
            results.append({
                "premium": premium,
                "revenue": best_revenue,
                "incentive": best_incentive,
            })
        return results


# Prediction API Endpoint
# ---------------------------------------------------------
# This endpoint receives customer data, performs preprocessing,
# loads the trained machine learning model, predicts renewal
# probabilities, and identifies the incentive that maximizes
# expected revenue.
@app.post("/predict")
def run_insurance(request: RevenueRenewal):
    try:
        # Extracting the input data from the API request.
        data = request.data

        # Converting the incoming list data into a Pandas
        # DataFrame using the feature names expected by the model.
        data = pd.DataFrame(
            data,
            columns=[
                'perc_premium_paid_by_cash_credit',
                'age_in_days',
                'Income',
                'Count_3-6_months_late',
                'Count_6-12_months_late',
                'Count_more_than_12_months_late',
                'application_underwriting_score',
                'no_of_premiums_paid',
                'sourcing_channel',
                'residence_area_type',
                'premium',
            ],
        )

        # Loading the previously trained imputer used for
        # handling missing values in the numerical features.
        imputer = joblib.load("Adarsh_Simple_Imputer.pkl")

        # Selecting all numerical columns from the input data.
        # num_col = data.describe().columns
        num_col = list(data.select_dtypes(include="number").columns)

        # Applying the saved imputer to the numerical columns
        # so that missing values are handled consistently with
        # the model training process.
        data[num_col] = imputer.transform(data[num_col])

        # Creating a new feature called Total_late by combining
        # all three categories of late premium payments.
        data["Total_late"] = data['Count_3-6_months_late']
        +data['Count_6-12_months_late']
        +data['Count_more_than_12_months_late']
        # Loading the trained insurance renewal prediction model.
        predictor = prediction()
        # Generating probability predictions using the trained model.
        # The second probability value [1] represents the probability
        # of the positive/renewal class.
        probabilities = predictor.predict_proba(data[[
            'perc_premium_paid_by_cash_credit', 'age_in_days', 'Income',
            'Total_late', 'application_underwriting_score',
            'no_of_premiums_paid', 'premium', 'residence_area_type',
            'sourcing_channel']])
        max_rev = predictor.optimize_revenue(data, probabilities)
        # Returning the final optimization results as
        # a JSON response from the API.
        return ({"Result": max_rev})
#   Catching any unexpected errors during data processing,
    # model prediction, or revenue optimization.
    except Exception as e:

        # Returning the error as an HTTP 500 response so that
        # the API client receives a meaningful error message.
        raise HTTPException(status_code=500, detail=str(e))
